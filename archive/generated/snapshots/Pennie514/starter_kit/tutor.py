def grover_qasm(target: str) -> str:
    """2 比特 Grover：一次查询精确命中 target（'00'|'01'|'10'|'11'）。

    结构：H⊗H → 相位标记 target → 扩散算子。相位标记用 X 把 target 映到 |11⟩，
    做 CZ，再 X 还原；CZ 用 H-CX-H 分解（适配器无 cz 门）。
    """
    if target not in ("00", "01", "10", "11"):
        raise ValueError("target 必须是 00/01/10/11")
    # counts 采用 little-endian（最右字符 = q[0]），target 字符串同此约定：
    # target[-1] -> q[0]，target[0] -> q[1]，保证「你选的串」与「柱状图上的串」一致。
    n = len(target)
    flip = "".join(f"x q[{n - 1 - i}];\n" for i, ch in enumerate(target) if ch == "0")
    oracle = flip + _CZ + flip
    diffuse = ("h q[0];\nh q[1];\n"
               "x q[0];\nx q[1];\n" + _CZ + "x q[0];\nx q[1];\n"
               "h q[0];\nh q[1];\n")
    return _H2 + "h q[0];\nh q[1];\n" + oracle + diffuse + "measure q -> c;\n"
