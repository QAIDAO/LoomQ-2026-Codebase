#!/usr/bin/env python3
"""Submit and query an OriginQ real-hardware Bell task.

The OriginQ API token is read only from ``ORIGINQ_API_TOKEN``.  It is never
written to the repository or included in the evidence files.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict


STARTER_KIT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = STARTER_KIT.parent
EVIDENCE_DIR = STARTER_KIT / "evidence" / "files"
QASM_PATH = STARTER_KIT / "circuits" / "bell.qasm"
TASK_PATH = EVIDENCE_DIR / "originq-bell-task.json"
RAW_RESULT_PATH = EVIDENCE_DIR / "originq-bell-raw.json"
RESULT_PATH = EVIDENCE_DIR / "originq-bell-result.json"
EVIDENCE_QASM_PATH = EVIDENCE_DIR / "originq-bell.qasm"
ORIGIN_IR_PATH = EVIDENCE_DIR / "originq-bell-originir.txt"

if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _token() -> str:
    token = os.environ.get("ORIGINQ_API_TOKEN", "").strip()
    if not token:
        raise RuntimeError(
            "ORIGINQ_API_TOKEN is not set. Read it securely with: "
            'read -s "ORIGINQ_API_TOKEN?OriginQ API token: "; '
            "export ORIGINQ_API_TOKEN; echo"
        )
    return token


def _cloud_machine():
    import pyqpanda as pq
    from pyqpanda.OriginService.QCloudMachine import QCloud

    machine = QCloud()
    machine.init_qvm(_token())
    return machine, pq


def _origin_ir() -> tuple[str, str]:
    from starter_kit.emitters.originq import emit_originq
    from starter_kit.parser import parse_qasm

    qasm = QASM_PATH.read_text(encoding="utf-8")
    origin_ir = emit_originq(
        parse_qasm(qasm),
        execution_compatible=True,
    )
    return qasm, origin_ir


def _write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def _probabilities_to_counts(
    probabilities: Dict[str, float],
    shots: int,
) -> Dict[str, int]:
    if not probabilities:
        raise ValueError("OriginQ returned an empty result")

    values = {str(key): float(value) for key, value in probabilities.items()}
    total = sum(values.values())
    if total <= 0:
        raise ValueError("OriginQ returned a zero-probability result")

    scaled = {
        key: value / total * shots
        for key, value in values.items()
    }
    counts = {key: int(value) for key, value in scaled.items()}
    remainder = shots - sum(counts.values())
    order = sorted(
        scaled,
        key=lambda key: scaled[key] - counts[key],
        reverse=True,
    )
    for key in order[:remainder]:
        counts[key] += 1
    return counts


def _device_name(chip_id: int) -> str:
    return f"origin_{chip_id}"


def _task_device(task_id: str) -> str:
    """Recover the submitted device for evidence generated by a later query."""
    try:
        payload = json.loads(TASK_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError):
        return "origin_unknown"
    if str(payload.get("job_id")) != str(task_id):
        return "origin_unknown"
    return str(payload.get("device") or "origin_unknown")


def submit(shots: int, confirmed: bool, chip_id: int = 72) -> int:
    if not confirmed:
        raise RuntimeError(
            "This creates a real QPU task and may consume quota. "
            "Re-run with --confirm-real-qpu after checking your account."
        )
    if shots <= 0:
        raise ValueError("shots must be positive")
    if chip_id <= 0:
        raise ValueError("chip id must be positive")

    qasm, origin_ir = _origin_ir()
    machine, pq = _cloud_machine()
    try:
        task_id = machine.async_real_chip_measure(
            prog=origin_ir,
            shot=shots,
            # The cloud can expose a new device before this pinned pyqpanda
            # version gains a named enum member. The API accepts a numeric id.
            chip_id=chip_id,
            is_amend=True,
            is_mapping=True,
            is_optimization=True,
            task_name="LoomQ Bell Hardware Evidence",
        )
    finally:
        machine.finalize()

    EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
    EVIDENCE_QASM_PATH.write_text(qasm, encoding="utf-8")
    ORIGIN_IR_PATH.write_text(origin_ir + "\n", encoding="utf-8")
    _write_json(
        TASK_PATH,
        {
            "platform": "OriginQ",
            "backend": "originq_wukong",
            "device": _device_name(chip_id),
            "chip_id": chip_id,
            "job_id": str(task_id),
            "shots": shots,
            "submitted_at": _utc_now(),
            "qasm_path": "evidence/files/originq-bell.qasm",
            "origin_ir_path": "evidence/files/originq-bell-originir.txt",
        },
    )

    print("OriginQ real-hardware task submitted.")
    print(f"job_id: {task_id}")
    print(f"Task metadata: {TASK_PATH}")
    print("Query later with:")
    print(
        "python starter_kit/examples/submit_originq_hardware.py "
        f"query {task_id} --shots {shots}"
    )
    return 0


def query(task_id: str, shots: int) -> int:
    if shots <= 0:
        raise ValueError("shots must be positive")

    machine, _pq = _cloud_machine()
    try:
        status, platform_result = machine.query_task_state_result(task_id)
    finally:
        machine.finalize()

    status_names = {
        1: "WAITING",
        2: "COMPUTING",
        3: "FINISHED",
        4: "FAILED",
    }
    status_name = status_names.get(int(status), f"UNKNOWN_{status}")
    queried_at = _utc_now()

    _write_json(
        RAW_RESULT_PATH,
        {
            "platform": "OriginQ",
            "job_id": task_id,
            "status": status_name,
            "queried_at": queried_at,
            "sdk_result": platform_result,
        },
    )

    print(f"job_id: {task_id}")
    print(f"status: {status_name}")

    if int(status) == 3:
        probabilities = {
            str(key): float(value)
            for key, value in platform_result.items()
        }
        counts = _probabilities_to_counts(probabilities, shots)
        _write_json(
            RESULT_PATH,
            {
                "backend": "originq_wukong",
                "job_id": task_id,
                "shots": shots,
                "counts": counts,
                "bit_order": "little",
                "timestamp": queried_at,
                "meta": {
                    "is_mock": False,
                    "device": _task_device(task_id),
                    "raw_result_path": "evidence/files/originq-bell-raw.json",
                    "probabilities_returned_by_sdk": probabilities,
                },
            },
        )
        print(json.dumps(counts, ensure_ascii=False, indent=2))
        print(f"Raw SDK result: {RAW_RESULT_PATH}")
        print(f"Normalized evidence: {RESULT_PATH}")
        return 0

    if int(status) == 4:
        print(f"Failed task response saved to {RAW_RESULT_PATH}")
        return 1

    print("The task is not finished yet. Run the same query command later.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Submit or query an OriginQ real-hardware Bell task"
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    submit_parser = subparsers.add_parser("submit")
    submit_parser.add_argument("--shots", type=int, default=1024)
    submit_parser.add_argument(
        "--chip-id",
        type=int,
        default=72,
        help="numeric OriginQ real-chip id (use 180 for Wukong 180)",
    )
    submit_parser.add_argument(
        "--confirm-real-qpu",
        action="store_true",
        help="confirm that a real QPU task may consume account quota",
    )

    query_parser = subparsers.add_parser("query")
    query_parser.add_argument("job_id")
    query_parser.add_argument("--shots", type=int, default=1024)

    args = parser.parse_args()
    if args.command == "submit":
        return submit(args.shots, args.confirm_real_qpu, args.chip_id)
    return query(args.job_id, args.shots)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError, ValueError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(2)
