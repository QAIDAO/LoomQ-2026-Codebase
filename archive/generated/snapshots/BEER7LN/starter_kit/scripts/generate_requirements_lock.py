#!/usr/bin/env python3
"""Resolve pinned direct requirements into an auditable transitive lock."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
DIRECT = ROOT / "requirements.txt"
LOCK = ROOT / "requirements-lock.txt"


def build_lock() -> str:
    if sys.version_info[:2] != (3, 10):
        raise RuntimeError(
            "generate the native SDK lock with Python 3.10 "
            "(Windows: py -3.10 scripts/generate_requirements_lock.py)"
        )
    with tempfile.TemporaryDirectory(prefix="loomq-lock-") as directory:
        report = Path(directory) / "pip-report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--report",
            str(report),
            "-r",
            str(DIRECT),
        ]
        subprocess.run(command, cwd=ROOT, check=True)
        payload = json.loads(report.read_text(encoding="utf-8"))

    resolved: dict[str, str] = {}
    for item in payload.get("install", []):
        metadata = item.get("metadata", {})
        name, version = metadata.get("name"), metadata.get("version")
        if not isinstance(name, str) or not isinstance(version, str):
            raise RuntimeError("pip report contains an unversioned distribution")
        key = _canonical_name(name)
        if key in resolved and resolved[key] != version:
            raise RuntimeError(f"resolver returned conflicting versions for {name}")
        resolved[key] = version
    if not resolved:
        raise RuntimeError("pip resolver report contains no distributions")

    direct_hash = hashlib.sha256(DIRECT.read_bytes()).hexdigest()
    pip_version = subprocess.run(
        [sys.executable, "-m", "pip", "--version"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    resolver = (
        pip_version.split(" from ", 1)[0]
        + f" (python {sys.version_info.major}.{sys.version_info.minor})"
    )
    lines = [
        "# LoomQ transitive dependency lock",
        "# Generated by: python scripts/generate_requirements_lock.py",
        f"# Direct requirements SHA256: {direct_hash}",
        f"# Resolver: {resolver}",
        f"# Target: CPython {platform.python_version()}, {platform.system()}-{platform.machine()}",
        "# Regenerate when requirements.txt or the Python 3.10 target changes.",
        "",
    ]
    lines.extend(f"{name}=={resolved[name]}" for name in sorted(resolved))
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if a fresh resolver report differs from requirements-lock.txt",
    )
    args = parser.parse_args()
    content = build_lock()
    if args.check:
        if not LOCK.exists() or LOCK.read_text(encoding="utf-8") != content:
            print("requirements-lock.txt is stale", file=sys.stderr)
            return 1
        print("requirements-lock.txt matches a fresh pip resolver report.")
        return 0
    LOCK.write_text(content, encoding="utf-8")
    print(f"Wrote {LOCK}")
    return 0


def _canonical_name(name: str) -> str:
    return name.strip().lower().replace("_", "-").replace(".", "-")


if __name__ == "__main__":
    raise SystemExit(main())
