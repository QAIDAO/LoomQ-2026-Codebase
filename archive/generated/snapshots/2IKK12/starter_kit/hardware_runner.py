"""Optional real-hardware execution for the local LoomQ web product.

The competition adapter remains local and dependency-free.  This module is
loaded only when a user explicitly chooses real hardware in the web UI.
Credentials stay in the standard AWS credential chain and environment; no
secret is accepted from, or returned to, the browser.
"""

from __future__ import annotations

import importlib.util
import os
from datetime import datetime, timezone
from typing import Any

try:
    from . import adapter
except ImportError:
    import adapter


def hardware_status() -> dict[str, Any]:
    sdk_installed = importlib.util.find_spec("braket") is not None
    device_configured = bool(os.environ.get("LOOMQ_BRAKET_DEVICE_ARN", "").strip())
    bucket_configured = bool(os.environ.get("LOOMQ_BRAKET_S3_BUCKET", "").strip())
    configured = sdk_installed and device_configured and bucket_configured
    missing = []
    if not sdk_installed:
        missing.append("amazon-braket-sdk")
    if not device_configured:
        missing.append("LOOMQ_BRAKET_DEVICE_ARN")
    if not bucket_configured:
        missing.append("LOOMQ_BRAKET_S3_BUCKET")
    return {
        "backends": [
            {
                "id": "braket_qpu",
                "name": "Amazon Braket 量子真机",
                "provider": "AWS Braket",
                "kind": "qpu",
                "configured": configured,
                "missing": missing,
                "cost": "paid",
                "queue": "device_dependent",
                "note": "需要 AWS 凭证、QPU Device ARN 和 S3 结果存储桶。提交会产生真实费用。",
            }
        ]
    }


def run_hardware(qasm: str, backend_id: str, shots: int) -> dict[str, Any]:
    if backend_id != "braket_qpu":
        raise ValueError(f"unsupported hardware backend: {backend_id}")
    status = hardware_status()["backends"][0]
    if not status["configured"]:
        raise RuntimeError("真机连接尚未配置：" + "、".join(status["missing"]))
    if not isinstance(shots, int) or isinstance(shots, bool) or not 1 <= shots <= 100000:
        raise ValueError("hardware shots must be an integer between 1 and 100000")

    from braket.aws import AwsDevice
    from braket.ir.openqasm import Program

    device_arn = os.environ["LOOMQ_BRAKET_DEVICE_ARN"].strip()
    if "/qpu/" not in device_arn:
        raise ValueError("LOOMQ_BRAKET_DEVICE_ARN 必须指向 Braket QPU，不能用云模拟器冒充真机")
    bucket = os.environ["LOOMQ_BRAKET_S3_BUCKET"].strip()
    prefix = os.environ.get("LOOMQ_BRAKET_S3_PREFIX", "loomq-web").strip() or "loomq-web"
    timeout = int(os.environ.get("LOOMQ_BRAKET_POLL_TIMEOUT_SECONDS", "900"))

    qasm3 = adapter.transpile(qasm, "braket")
    device = AwsDevice(device_arn)
    task = device.run(
        Program(source=qasm3),
        (bucket, prefix),
        shots=shots,
        poll_timeout_seconds=timeout,
        poll_interval_seconds=5,
    )
    result = task.result()
    if result is None:
        raise RuntimeError(f"Braket 任务未返回结果，当前状态：{task.state()}")
    counts = {str(key): int(value) for key, value in result.measurement_counts.items()}
    if sum(counts.values()) != shots:
        raise RuntimeError("Braket 真机返回的 counts 与 shots 不一致")
    return {
        "backend": device_arn,
        "job_id": task.id,
        "shots": shots,
        "counts": counts,
        "bit_order": "little",
        "timestamp": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "meta": {
            "execution_type": "real_hardware",
            "provider": "AWS Braket",
            "device_name": getattr(device, "name", None),
            "task_state": task.state(),
            "console_traceable": True,
            "source_format": "OpenQASM 3.0 generated by LoomQ L1",
        },
    }
